import os from "node:os";
import path from "node:path";
import { resolveGlobalNyxowlPaths } from "../../core/paths.ts";
import { compileAllAgentsAndCommands } from "../compiler.ts";
import { upsertJsoncPropertyFile, writeTrackedFile } from "../manifest.ts";
import { resolveNyxowlCliCommand } from "./claude.ts";

export interface CursorPackageResult {
  packageDir: string;
  rulePath: string;
  mcpConfigPath: string;
  worktreeMode: "in-repo";
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

export function generateCursorHostPackage(options?: {
  nyxowlHome?: string;
  userCursorDir?: string;
  projectPath?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): CursorPackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const packageDir = path.join(globalPaths.hostsDir, "cursor");
  const userCursorDir = options?.userCursorDir ?? path.join(os.homedir(), ".cursor");
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  const primary = bundle.agents.find((a) => a.contract.id === "nyxowl") ?? bundle.agents[0]!;
  const mdcContent = [
    "---",
    "description: Nyxowl Principal Tech Lead & 7-Engine Runtime Orchestrator (generated by nyxowl v0.1.0)",
    "alwaysApply: true",
    "---",
    "<!-- generated by nyxowl v0.1.0 -->",
    primary.compiledPrompt.trim(),
    "",
  ].join("\n");

  // Write to ~/.nyxowl/hosts/cursor/nyxowl.mdc AND user-level ~/.cursor/rules/nyxowl.mdc (recorded in manifest)
  writeTrackedFile({
    targetPath: path.join(packageDir, "nyxowl.mdc"),
    content: mdcContent,
    host: "cursor",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const rulePath = path.join(userCursorDir, "rules", "nyxowl.mdc");
  writeTrackedFile({
    targetPath: rulePath,
    content: mdcContent,
    host: "cursor",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const mcpConfigPath = path.join(userCursorDir, "mcp.json");
  upsertJsoncPropertyFile({
    targetPath: mcpConfigPath,
    jsonPath: ["mcpServers", "nyxowl"],
    value: {
      command: cliCmd.command,
      args: [...cliCmd.args, "mcp"],
      env: {
        NYXOWL_SESSION: "1",
      },
    },
    host: "cursor",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const targetDir = options?.projectPath ?? process.cwd();
  return {
    packageDir,
    rulePath,
    mcpConfigPath,
    worktreeMode: "in-repo",
    launchArgs: [targetDir],
    launchEnv: {
      NYXOWL_SESSION: "1",
      NYXOWL_WORKTREE_FALLBACK: "in-repo",
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

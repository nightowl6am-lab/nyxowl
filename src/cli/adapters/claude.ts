export function buildClaudeSessionSettings(options: {
  worktreeRoot: string;
}): Record<string, unknown> {
  return {
    _comment: "generated by nyxowl v0.1.0",
    permissions: {
      deny: [...CLAUDE_SECRET_DENY_RULES],
      ask: [...CLAUDE_REDLINE_ASK_RULES],
      allow: [...CLAUDE_ALLOW_RULES],
    },
    additionalDirectories: [options.worktreeRoot],
    sandbox: {
      enabled: true,
      autoAllowBashIfSandboxed: true,
      writablePaths: [options.worktreeRoot],
    },
  };
}

/**
 * Evaluates Claude Code's permission precedence (`deny` checked first -> `ask` -> `allow` -> default `ask`)
 * against a tool expression such as `Read(.env)`, `Read(.env.local)`, `Read(.env.example)`, or `Bash(gh pr merge)`.
 */
export function evaluateClaudePermissionPrecedence(
  settings: {
    permissions: { deny: string[]; ask: string[]; allow: string[] };
  },
  toolCallExpr: string,
): "deny" | "ask" | "allow" {
  const matchRule = (rule: string, target: string): boolean => {
    const regexStr =
      "^" +
      rule.replace(/(\*\*\/|\*\*|\*|[.+^${}()|[\]\\])/g, (m) => {
        if (m === "**/") return "(?:.+/)?";
        if (m === "**") return ".*";
        if (m === "*") return ".*";
        return `\\${m}`;
      }) +
      "$";
    return new RegExp(regexStr).test(target);
  };

  for (const d of settings.permissions.deny) {
    if (matchRule(d, toolCallExpr)) return "deny";
  }
  for (const a of settings.permissions.ask) {
    if (matchRule(a, toolCallExpr)) return "ask";
  }
  for (const al of settings.permissions.allow) {
    if (matchRule(al, toolCallExpr)) return "allow";
  }
  return "ask";
}

export function generateClaudeHostPackage(options?: {
  nyxowlHome?: string;
  projectPath?: string;
  worktreeRoot?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): ClaudePackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const pluginDir = path.join(globalPaths.hostsDir, "claude");
  const worktreeRoot = options?.worktreeRoot ?? globalPaths.worktreesDir;
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  // 1. .claude-plugin/plugin.json & plugin.json
  const pluginManifest = `${JSON.stringify(
    {
      _comment: "generated by nyxowl v0.1.0",
      name: "nyxowl",
      version: "0.1.0",
      description:
        "Nyxowl — Principal Tech Lead, 9 Subagents & 7-Engine Runtime MCP (generated by nyxowl v0.1.0)",
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: path.join(pluginDir, ".claude-plugin", "plugin.json"),
    content: pluginManifest,
    host: "claude",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });
  writeTrackedFile({
    targetPath: path.join(pluginDir, "plugin.json"),
    content: pluginManifest,
    host: "claude",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 2. Agents (agents/nyxowl.md + agents/nyx-*.md) with per-role `tools:` allowlist (§4.4, §8.3)
  for (const agent of bundle.agents) {
    const md = [
      "---",
      `name: ${agent.contract.id}`,
      `description: ${JSON.stringify(agent.contract.description)}`,
      `tools: ${agent.claudeToolsAllowlist.join(", ")}`,
      "---",
      "<!-- generated by nyxowl v0.1.0 -->",
      agent.compiledPrompt.trim(),
      "",
    ].join("\n");
    writeTrackedFile({
      targetPath: path.join(pluginDir, "agents", `${agent.contract.id}.md`),
      content: md,
      host: "claude",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  // 3. Commands (commands/nyx-*.md)
  for (const cmd of bundle.commands) {
    const md = [
      "---",
      `description: ${JSON.stringify(cmd.description)}`,
      "---",
      "<!-- generated by nyxowl v0.1.0 -->",
      cmd.bodyMarkdown.trim(),
      "",
    ].join("\n");
    writeTrackedFile({
      targetPath: path.join(pluginDir, "commands", `${cmd.name}.md`),
      content: md,
      host: "claude",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  // 4. Resolved skills (skills/<name>/SKILL.md, excluding placeholders)
  for (const skill of bundle.allResolvedSkills) {
    const srcMd = path.join(skill.sourcePath, "SKILL.md");
    if (fs.existsSync(srcMd)) {
      const content = fs.readFileSync(srcMd, "utf8");
      writeTrackedFile({
        targetPath: path.join(pluginDir, "skills", skill.name, "SKILL.md"),
        content,
        host: "claude",
        ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
      });
    }
  }

  // 5. Hooks (hooks/hooks.json)
  const hooksJson = `${JSON.stringify(
    {
      _comment: "generated by nyxowl v0.1.0",
      hooks: {
        PreToolUse: [
          {
            matcher: "Bash|Read|Grep|Glob",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook guard`,
              },
            ],
          },
          {
            matcher: "Edit|Write|MultiEdit",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook edit-guard`,
              },
            ],
          },
        ],
        SessionStart: [
          {
            matcher: ".*",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook session-start`,
              },
            ],
          },
        ],
        PreCompact: [
          {
            matcher: ".*",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook pre-compact`,
              },
            ],
          },
        ],
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: path.join(pluginDir, "hooks", "hooks.json"),
    content: hooksJson,
    host: "claude",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 6. .mcp.json
  const mcpConfigPath = path.join(pluginDir, ".mcp.json");
  const mcpJson = `${JSON.stringify(
    {
      _comment: "generated by nyxowl v0.1.0",
      mcpServers: {
        nyxowl: {
          command: cliCmd.command,
          args: [...cliCmd.args, "mcp"],
          env: {
            NYXOWL_SESSION: "1",
            ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
          },
        },
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: mcpConfigPath,
    content: mcpJson,
    host: "claude",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 7. Session settings.json
  const settingsPath = path.join(pluginDir, "settings.json");
  const settingsObj = buildClaudeSessionSettings({ worktreeRoot });
  writeTrackedFile({
    targetPath: settingsPath,
    content: `${JSON.stringify(settingsObj, null, 2)}\n`,
    host: "claude",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  return {
    pluginDir,
    settingsPath,
    mcpConfigPath,
    launchArgs: [
      "--plugin-dir",
      pluginDir,
      "--settings",
      settingsPath,
      "--agent",
      "nyxowl",
    ],
    launchEnv: {
      NYXOWL_SESSION: "1",
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

import os from "node:os";
import path from "node:path";
import { resolveGlobalNyxowlPaths } from "../../core/paths.ts";
import { compileAllAgentsAndCommands } from "../compiler.ts";
import {
  upsertJsoncPropertyFile,
  upsertManagedBlockFile,
  writeTrackedFile,
} from "../manifest.ts";
import { resolveNyxowlCliCommand } from "./claude.ts";

export interface WindsurfPackageResult {
  packageDir: string;
  rulePath: string;
  mcpConfigPath: string;
  worktreeMode: "in-repo";
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

export function generateWindsurfHostPackage(options?: {
  nyxowlHome?: string;
  userWindsurfDir?: string;
  projectPath?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): WindsurfPackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const packageDir = path.join(globalPaths.hostsDir, "windsurf");
  const userWindsurfDir =
    options?.userWindsurfDir ?? path.join(os.homedir(), ".codeium", "windsurf");
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  const primary = bundle.agents.find((a) => a.contract.id === "nyxowl") ?? bundle.agents[0]!;
  const ruleBlock = [
    "# Nyxowl Principal Tech Lead & 7-Engine Runtime Orchestrator (generated by nyxowl v0.1.0)",
    primary.compiledPrompt.trim(),
  ].join("\n");

  writeTrackedFile({
    targetPath: path.join(packageDir, "nyxowl.md"),
    content: `<!-- generated by nyxowl v0.1.0 -->\n${primary.compiledPrompt.trim()}\n`,
    host: "windsurf",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const rulePath = path.join(userWindsurfDir, "memories", "global_rules.md");
  upsertManagedBlockFile({
    targetPath: rulePath,
    blockBody: ruleBlock,
    host: "windsurf",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const mcpConfigPath = path.join(userWindsurfDir, "mcp_config.json");
  upsertJsoncPropertyFile({
    targetPath: mcpConfigPath,
    jsonPath: ["mcpServers", "nyxowl"],
    value: {
      command: cliCmd.command,
      args: [...cliCmd.args, "mcp"],
      env: {
        NYXOWL_SESSION: "1",
      },
    },
    host: "windsurf",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const targetDir = options?.projectPath ?? process.cwd();
  return {
    packageDir,
    rulePath,
    mcpConfigPath,
    worktreeMode: "in-repo",
    launchArgs: [targetDir],
    launchEnv: {
      NYXOWL_SESSION: "1",
      NYXOWL_WORKTREE_FALLBACK: "in-repo",
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

export interface OpenCodePackageResult {
  packageDir: string;
  configPath: string;
  pluginPath: string;
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

/**
 * Builds OpenCode's last-match-wins permission object (§1.2.1, §8.4):
 * Broad `.env*` denies MUST come BEFORE `.env.example` / `.env.sample` / `.env.template` allows!
 */
export function buildOpenCodePermissions(worktreeRoot: string): {
  read: Record<string, "allow" | "deny" | "ask">;
  edit: Record<string, "allow" | "deny" | "ask">;
  bash: Record<string, "allow" | "deny" | "ask">;
  webfetch: "deny";
  external_directory: Record<string, "allow" | "deny">;
} {
  return {
    read: {
      "*": "allow",
      ".env*": "deny",
      "**/.env*": "deny",
      "**/*.pem": "deny",
      "**/*.key": "deny",
      "**/*.p12": "deny",
      "**/*credentials*.json": "deny",
      "**/*service-account*.json": "deny",
      "~/.aws/credentials": "deny",
      "~/.ssh/id_*": "deny",
      "**/.npmrc": "deny",
      "**/.pypirc": "deny",
      "**/.netrc": "deny",
      "**/.git-credentials": "deny",
      "~/.nyxowl/secrets/**": "deny",
      "~/.nyxowl/projects/**": "deny",
      // Example-allows MUST appear AFTER `.env*` denies because OpenCode last-match wins!
      ".env.example": "allow",
      "**/.env.example": "allow",
      ".env.sample": "allow",
      "**/.env.sample": "allow",
      ".env.template": "allow",
      "**/.env.template": "allow",
    },
    edit: {
      "*": "allow",
      ".env*": "deny",
      "**/.env*": "deny",
      "~/.nyxowl/secrets/**": "deny",
      "~/.nyxowl/projects/**": "deny",
      ".github/workflows/**": "ask",
      ".env.example": "allow",
      "**/.env.example": "allow",
      ".env.sample": "allow",
      "**/.env.sample": "allow",
      ".env.template": "allow",
      "**/.env.template": "allow",
    },
    bash: {
      "*": "allow",
      "printenv*": "deny",
      "env": "deny",
      "export -p*": "deny",
      "gh auth token*": "deny",
      "git config --list*": "deny",
      "gh pr merge*": "ask",
      "git push --force*": "ask",
      "git push -f*": "ask",
      "git push origin main*": "ask",
      "git push origin master*": "ask",
      "npm publish*": "ask",
      "cargo publish*": "ask",
      "docker push*": "ask",
      "terraform apply*": "ask",
      "terraform destroy*": "ask",
      "kubectl delete*": "ask",
    },
    webfetch: "deny",
    external_directory: {
      [worktreeRoot]: "allow",
    },
  };
}

/**
 * Evaluates OpenCode's last-match-wins permission map against a target path/command.
 */
export function evaluateOpenCodeLastMatchPermission(
  ruleMap: Record<string, "allow" | "deny" | "ask">,
  target: string,
): "allow" | "deny" | "ask" {
  const matchGlob = (pattern: string, input: string): boolean => {
    if (pattern === "*") return true;
    const regexStr =
      "^" +
      pattern.replace(/(\*\*\/|\*\*|\*|[.+^${}()|[\]\\])/g, (m) => {
        if (m === "**/") return "(?:.+/)?";
        if (m === "**") return ".*";
        if (m === "*") return "[^/]*";
        return `\\${m}`;
      }) +
      "$";
    return new RegExp(regexStr).test(input);
  };

  let decision: "allow" | "deny" | "ask" = "ask";
  for (const [pattern, action] of Object.entries(ruleMap)) {
    if (matchGlob(pattern, target)) {
      decision = action;
    }
  }
  return decision;
}

export function generateOpenCodeHostPackage(options?: {
  nyxowlHome?: string;
  projectPath?: string;
  worktreeRoot?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): OpenCodePackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const packageDir = path.join(globalPaths.hostsDir, "opencode");
  const worktreeRoot = options?.worktreeRoot ?? globalPaths.worktreesDir;
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  const allNyxToolNames = ALL_NYX_TOOLS.map((t) => t.name);
  const agentsConfig: Record<string, unknown> = {};

  for (const agent of bundle.agents) {
    const promptRelPath = `./prompts/${agent.contract.id}.md`;
    writeTrackedFile({
      targetPath: path.join(packageDir, "prompts", `${agent.contract.id}.md`),
      content: `<!-- generated by nyxowl v0.1.0 -->\n${agent.compiledPrompt.trim()}\n`,
      host: "opencode",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });

    // Per-agent tool scoping (§4.4, §8.4): enable only this role's nyx_tools
    const allowedSet = new Set(
      agent.contract.nyx_tools.map((t) => (t.startsWith("nyx_") ? t : `nyx_${t}`)),
    );
    const toolToggleMap: Record<string, boolean> = {
      read: agent.contract.host_tools.read === "allow",
      edit: agent.contract.host_tools.edit !== "deny",
      write: agent.contract.host_tools.write !== "deny",
      bash: agent.contract.host_tools.bash !== "deny",
      webfetch: false,
    };
    for (const fullToolName of allNyxToolNames) {
      toolToggleMap[`nyxowl_${fullToolName}`] = allowedSet.has(fullToolName);
    }

    agentsConfig[agent.contract.id] = {
      mode: agent.contract.mode,
      description: agent.contract.description,
      prompt: `{file:${promptRelPath}}`,
      tools: toolToggleMap,
    };
  }

  const commandsConfig: Record<string, unknown> = {};
  for (const cmd of bundle.commands) {
    commandsConfig[cmd.name] = {
      description: cmd.description,
      template: cmd.bodyMarkdown,
    };
  }

  // Copy resolved skills into packageDir/skills
  for (const skill of bundle.allResolvedSkills) {
    const srcMd = path.join(skill.sourcePath, "SKILL.md");
    if (fs.existsSync(srcMd)) {
      writeTrackedFile({
        targetPath: path.join(packageDir, "skills", skill.name, "SKILL.md"),
        content: fs.readFileSync(srcMd, "utf8"),
        host: "opencode",
        ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
      });
    }
  }

  // Write plugins/nyxowl.ts
  const pluginPath = path.join(packageDir, "plugins", "nyxowl.ts");
  const pluginCode = [
    "// generated by nyxowl v0.1.0",
    'import { execFileSync } from "node:child_process";',
    "",
    "export const NyxowlOpenCodePlugin = async () => ({",
    '  "tool.execute.before": async (input: { tool: string; args: Record<string, unknown>; agent?: string }) => {',
    "    const payload = JSON.stringify({",
    "      tool_name: input.tool,",
    "      tool_input: input.args,",
    '      agent_name: input.agent ?? "nyxowl",',
    "    });",
    '    const subcommand = /edit|write|patch/i.test(input.tool) ? "edit-guard" : "guard";',
    `    execFileSync(${JSON.stringify(cliCmd.command)}, [${cliCmd.args.map((a) => JSON.stringify(a)).join(", ")}, "hook", subcommand], {`,
    "      input: payload,",
    '      env: { ...process.env, NYXOWL_SESSION: "1", NYXOWL_HOOK_EXIT_ON_DENY: "1" },',
    '      stdio: ["pipe", "pipe", "pipe"],',
    "    });",
    "  },",
    '  "experimental.session.compacting": async (_input: unknown, output: { context: string[] }) => {',
    "    try {",
    `      const out = execFileSync(${JSON.stringify(cliCmd.command)}, [${cliCmd.args.map((a) => JSON.stringify(a)).join(", ")}, "hook", "pre-compact"], {`,
    '        input: JSON.stringify({ agent_name: "nyxowl" }),',
    '        env: { ...process.env, NYXOWL_SESSION: "1" },',
    '        encoding: "utf8",',
    "      });",
    "      if (out.trim()) {",
    "        const parsed = JSON.parse(out) as { additionalContext?: string };",
    "        if (parsed.additionalContext) output.context.push(parsed.additionalContext);",
    "      }",
    "    } catch {",
    "      // Fail-safe no-op for compaction hook",
    "    }",
    "  },",
    "});",
    "",
  ].join("\n");
  writeTrackedFile({
    targetPath: pluginPath,
    content: pluginCode,
    host: "opencode",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // Write opencode.json
  const configPath = path.join(packageDir, "opencode.json");
  const opencodeConfig = {
    // nyx-allow: hardcoded-url — official OpenCode JSON schema URL
    $schema: "https://opencode.ai/config.json",
    _comment: "generated by nyxowl v0.1.0",
    default_agent: "nyxowl",
    plugin: [pluginPath],
    mcp: {
      nyxowl: {
        type: "local",
        command: [cliCmd.command, ...cliCmd.args, "mcp"],
        enabled: true,
        environment: {
          NYXOWL_SESSION: "1",
          ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
        },
      },
    },
    permission: buildOpenCodePermissions(worktreeRoot),
    agent: agentsConfig,
    command: commandsConfig,
  };
  writeTrackedFile({
    targetPath: configPath,
    content: `${JSON.stringify(opencodeConfig, null, 2)}\n`,
    host: "opencode",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const targetDir = options?.projectPath ?? process.cwd();
  return {
    packageDir,
    configPath,
    pluginPath,
    launchArgs: [targetDir, "--agent", "nyxowl"],
    launchEnv: {
      NYXOWL_SESSION: "1",
      OPENCODE_CONFIG: configPath,
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

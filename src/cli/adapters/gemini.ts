import path from "node:path";
import { NYXOWL_VERSION } from "../../core/version.ts";
import * as smolToml from "smol-toml";
import { resolveGlobalNyxowlPaths } from "../../core/paths.ts";
import { compileAllAgentsAndCommands } from "../compiler.ts";
import { writeTrackedFile } from "../manifest.ts";
import { resolveNyxowlCliCommand } from "./claude.ts";

export interface GeminiPackageResult {
  extensionDir: string;
  extensionManifestPath: string;
  settingsPath: string;
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

export function generateGeminiHostPackage(options?: {
  nyxowlHome?: string;
  projectPath?: string;
  worktreeRoot?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): GeminiPackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const extensionDir = path.join(globalPaths.hostsDir, "gemini");
  const worktreeRoot = options?.worktreeRoot ?? globalPaths.worktreesDir;
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  const primary = bundle.agents.find((a) => a.contract.id === "nyxowl") ?? bundle.agents[0]!;
  const geminiMdPath = path.join(extensionDir, "GEMINI.md");
  writeTrackedFile({
    targetPath: geminiMdPath,
    content: [
      `<!-- generated by nyxowl v${NYXOWL_VERSION} -->`,
      primary.compiledPrompt.trim(),
      "",
      "## Sequential Role Execution",
      "Execute specialist roles sequentially (`nyx-product` -> `nyx-architect` -> `nyx-db`/`nyx-api`/`nyx-ui` -> `nyx-sec`/`nyx-probe`), emitting `subagent-summary-v1` JSON at every role transition.",
      "",
    ].join("\n"),
    host: "gemini",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  for (const cmd of bundle.commands) {
    const tomlContent = `# generated by nyxowl v${NYXOWL_VERSION}\n${smolToml.stringify({
      description: cmd.description,
      prompt: cmd.bodyMarkdown,
    }).trim()}\n`;
    writeTrackedFile({
      targetPath: path.join(extensionDir, "commands", `${cmd.name}.toml`),
      content: tomlContent,
      host: "gemini",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  const extensionManifestPath = path.join(extensionDir, "gemini-extension.json");
  const extJson = `${JSON.stringify(
    {
      _comment: `generated by nyxowl v${NYXOWL_VERSION}`,
      name: "nyxowl",
      version: NYXOWL_VERSION,
      description: `Nyxowl Principal Tech Lead & 7-Engine Runtime MCP (generated by nyxowl v${NYXOWL_VERSION})`,
      contextFileName: "GEMINI.md",
      mcpServers: {
        nyxowl: {
          command: cliCmd.command,
          args: [...cliCmd.args, "mcp"],
          env: {
            NYXOWL_SESSION: "1",
            ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
          },
        },
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: extensionManifestPath,
    content: extJson,
    host: "gemini",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const settingsPath = path.join(extensionDir, "settings.json");
  const settingsJson = `${JSON.stringify(
    {
      _comment: `generated by nyxowl v${NYXOWL_VERSION}`,
      includeDirectories: [worktreeRoot],
      hooks: {
        BeforeTool: [
          {
            matcher: "run_shell_command|read_file",
            command: `${cliCmd.shellHookPrefix} hook guard`,
          },
          {
            matcher: "write_file|replace",
            command: `${cliCmd.shellHookPrefix} hook edit-guard`,
          },
        ],
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: settingsPath,
    content: settingsJson,
    host: "gemini",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  return {
    extensionDir,
    extensionManifestPath,
    settingsPath,
    launchArgs: [
      "--extensions",
      extensionDir,
      "--include-directories",
      worktreeRoot,
    ],
    launchEnv: {
      NYXOWL_SESSION: "1",
      GEMINI_CLI_SYSTEM_SETTINGS_PATH: settingsPath,
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

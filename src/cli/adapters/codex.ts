import fs from "node:fs";
import { NYXOWL_VERSION } from "../../core/version.ts";
import path from "node:path";
import * as smolToml from "smol-toml";
import { resolveGlobalNyxowlPaths } from "../../core/paths.ts";
import { buildCompactCodexAgentsBlock, compileAllAgentsAndCommands } from "../compiler.ts";
import { upsertManagedBlockFile, writeTrackedFile } from "../manifest.ts";
import { resolveNyxowlCliCommand } from "./claude.ts";

export interface CodexPackageResult {
  packageDir: string;
  configTomlPath: string;
  instructionsPath: string;
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

export function generateCodexHostPackage(options?: {
  nyxowlHome?: string;
  projectPath?: string;
  worktreeRoot?: string;
  dnaTags?: Iterable<string>;
  userCodexHome?: string;
  writeUserFallbackBlock?: boolean;
  pkgRoot?: string;
}): CodexPackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const packageDir = path.join(globalPaths.hostsDir, "codex");
  const worktreeRoot = options?.worktreeRoot ?? globalPaths.worktreesDir;
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  const primary = bundle.agents.find((a) => a.contract.id === "nyxowl") ?? bundle.agents[0]!;
  const instructionsPath = path.join(packageDir, "AGENTS.md");
  const sequentialNotes = [
    `<!-- generated by nyxowl v${NYXOWL_VERSION} -->`,
    primary.compiledPrompt.trim(),
    "",
    "## Sequential Role Execution (Single-Context Host Mode)",
    "When running on hosts without native subagent spawning, execute roles sequentially (`nyx-product` -> `nyx-architect` -> `nyx-db`/`nyx-api`/`nyx-ui` -> `nyx-sec`/`nyx-probe`), emitting a valid `subagent-summary-v1` JSON block at every role switch.",
    "",
  ].join("\n");

  writeTrackedFile({
    targetPath: instructionsPath,
    content: sequentialNotes,
    host: "codex",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  for (const skill of bundle.allResolvedSkills) {
    const srcMd = path.join(skill.sourcePath, "SKILL.md");
    if (fs.existsSync(srcMd)) {
      writeTrackedFile({
        targetPath: path.join(packageDir, "skills", skill.name, "SKILL.md"),
        content: fs.readFileSync(srcMd, "utf8"),
        host: "codex",
        ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
      });
    }
  }

  const configTomlObj = {
    profile: "nyxowl",
    profiles: {
      nyxowl: {
        sandbox_mode: "workspace-write",
        approval_policy: "on-request",
        writable_roots: [worktreeRoot],
        instructions_file: instructionsPath,
      },
    },
    mcp_servers: {
      nyxowl: {
        command: cliCmd.command,
        args: [...cliCmd.args, "mcp"],
        env: {
          NYXOWL_SESSION: "1",
          ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
        },
      },
    },
  };

  const configTomlPath = path.join(packageDir, "config.toml");
  const tomlString = `# generated by nyxowl v${NYXOWL_VERSION}\n${smolToml.stringify(configTomlObj).trim()}\n`;
  writeTrackedFile({
    targetPath: configTomlPath,
    content: tomlString,
    host: "codex",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  if (options?.writeUserFallbackBlock && options.userCodexHome) {
    upsertManagedBlockFile({
      targetPath: path.join(options.userCodexHome, "AGENTS.md"),
      blockBody: buildCompactCodexAgentsBlock(),
      host: "codex",
      ...(options.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  const targetDir = options?.projectPath ?? process.cwd();
  return {
    packageDir,
    configTomlPath,
    instructionsPath,
    launchArgs: ["--profile", "nyxowl", "-C", targetDir],
    launchEnv: {
      NYXOWL_SESSION: "1",
      CODEX_HOME: packageDir,
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}

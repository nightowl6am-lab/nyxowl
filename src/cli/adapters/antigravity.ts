import fs from "node:fs";
import { NYXOWL_VERSION } from "../../core/version.ts";
import path from "node:path";
import { resolveGlobalNyxowlPaths } from "../../core/paths.ts";
import { compileAllAgentsAndCommands } from "../compiler.ts";
import { writeTrackedFile } from "../manifest.ts";
import { buildClaudeSessionSettings, resolveNyxowlCliCommand } from "./claude.ts";

export interface AntigravityPackageResult {
  pluginDir: string;
  settingsPath: string;
  mcpConfigPath: string;
  launchArgs: string[];
  launchEnv: Record<string, string>;
}

const MAX_AGY_SKILL_BYTES = 23_000;

function capSkillMarkdownForAntigravity(rawMd: string): string {
  if (Buffer.byteLength(rawMd, "utf8") <= MAX_AGY_SKILL_BYTES) {
    return rawMd;
  }
  return `${rawMd.slice(0, MAX_AGY_SKILL_BYTES - 100)}\n\n<!-- truncated to 24KB Antigravity skill body limit -->\n`;
}

export function generateAntigravityHostPackage(options?: {
  nyxowlHome?: string;
  projectPath?: string;
  worktreeRoot?: string;
  dnaTags?: Iterable<string>;
  pkgRoot?: string;
}): AntigravityPackageResult {
  const globalPaths = resolveGlobalNyxowlPaths(options?.nyxowlHome);
  const pluginDir = path.join(globalPaths.hostsDir, "antigravity");
  const worktreeRoot = options?.worktreeRoot ?? globalPaths.worktreesDir;
  const cliCmd = resolveNyxowlCliCommand(options?.pkgRoot);

  const bundle = compileAllAgentsAndCommands({
    ...(options?.dnaTags ? { dnaTags: options.dnaTags } : {}),
    includeConditionalAll: !options?.dnaTags,
    ...(options?.pkgRoot ? { pkgRoot: options.pkgRoot } : {}),
  });

  // 1. .antigravity-plugin/plugin.json + assets/logo.svg
  const pluginJson = `${JSON.stringify(
    {
      name: "nyxowl",
      version: NYXOWL_VERSION,
      description:
        `Nyxowl — Principal Tech Lead, 9 Subagents & 7-Engine Runtime MCP (generated by nyxowl v${NYXOWL_VERSION})`,
      logo: "assets/logo.svg",
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: path.join(pluginDir, ".antigravity-plugin", "plugin.json"),
    content: pluginJson,
    host: "antigravity",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><circle cx="32" cy="32" r="30" fill="#111827"/><circle cx="22" cy="28" r="6" fill="#38bdf8"/><circle cx="42" cy="28" r="6" fill="#38bdf8"/></svg>\n`;
  writeTrackedFile({
    targetPath: path.join(pluginDir, "assets", "logo.svg"),
    content: logoSvg,
    host: "antigravity",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 2. Agents (agents/nyxowl.md + agents/nyx-*.md)
  for (const agent of bundle.agents) {
    const md = [
      "---",
      `name: ${agent.contract.id}`,
      `description: ${JSON.stringify(agent.contract.description)}`,
      "---",
      `<!-- generated by nyxowl v${NYXOWL_VERSION} -->`,
      agent.compiledPrompt.trim(),
      "",
    ].join("\n");
    writeTrackedFile({
      targetPath: path.join(pluginDir, "agents", `${agent.contract.id}.md`),
      content: md,
      host: "antigravity",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  // 3. Commands delivered as Antigravity skills (skills/nyx-*/SKILL.md) per Antigravity plugin spec
  for (const cmd of bundle.commands) {
    const md = [
      "---",
      `name: ${cmd.name}`,
      `description: ${JSON.stringify(cmd.description)}`,
      "---",
      `<!-- generated by nyxowl v${NYXOWL_VERSION} -->`,
      cmd.bodyMarkdown.trim(),
      "",
    ].join("\n");
    writeTrackedFile({
      targetPath: path.join(pluginDir, "skills", cmd.name, "SKILL.md"),
      content: md,
      host: "antigravity",
      ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
    });
  }

  // 4. Resolved third-party skills (skills/<name>/SKILL.md, capped to 24KB)
  for (const skill of bundle.allResolvedSkills) {
    const srcMd = path.join(skill.sourcePath, "SKILL.md");
    if (fs.existsSync(srcMd)) {
      const capped = capSkillMarkdownForAntigravity(fs.readFileSync(srcMd, "utf8"));
      writeTrackedFile({
        targetPath: path.join(pluginDir, "skills", skill.name, "SKILL.md"),
        content: capped,
        host: "antigravity",
        ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
      });
    }
  }

  // 5. Hooks at plugin root (hooks.json) following Antigravity hooks.md spec:
  // PreToolUse is grouped ({ matcher, hooks }), SessionStart is flat ([{ type, command }])
  const hooksJson = `${JSON.stringify(
    {
      "nyxowl-guards": {
        PreToolUse: [
          {
            matcher: "run_command|read_file|grep_search|find_by_name",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook guard`,
              },
            ],
          },
          {
            matcher: "edit_file|write_file|replace_file_content|multi_replace_file_content",
            hooks: [
              {
                type: "command",
                command: `${cliCmd.shellHookPrefix} hook edit-guard`,
              },
            ],
          },
        ],
        SessionStart: [
          {
            type: "command",
            command: `${cliCmd.shellHookPrefix} hook session-start`,
          },
        ],
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: path.join(pluginDir, "hooks.json"),
    content: hooksJson,
    host: "antigravity",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 6. MCP servers at plugin root (mcp_config.json)
  const mcpConfigPath = path.join(pluginDir, "mcp_config.json");
  const mcpJson = `${JSON.stringify(
    {
      mcpServers: {
        nyxowl: {
          command: cliCmd.command,
          args: [...cliCmd.args, "mcp"],
          env: {
            NYXOWL_SESSION: "1",
            ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
          },
        },
      },
    },
    null,
    2,
  )}\n`;
  writeTrackedFile({
    targetPath: mcpConfigPath,
    content: mcpJson,
    host: "antigravity",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  // 7. Session settings file outside pluginDir so `agy plugin validate` stays 100% clean
  const settingsPath = path.join(globalPaths.hostsDir, "antigravity-settings.json");
  const settingsObj = buildClaudeSessionSettings({ worktreeRoot });
  writeTrackedFile({
    targetPath: settingsPath,
    content: `${JSON.stringify(settingsObj, null, 2)}\n`,
    host: "antigravity",
    ...(options?.nyxowlHome ? { nyxowlHome: options.nyxowlHome } : {}),
  });

  const targetDir = options?.projectPath ?? process.cwd();
  return {
    pluginDir,
    settingsPath,
    mcpConfigPath,
    launchArgs: [
      "--agent",
      "nyxowl",
      "--add-dir",
      worktreeRoot,
      "--sandbox",
      "--mode",
      "agent",
      "--settings",
      settingsPath,
      targetDir,
    ],
    launchEnv: {
      NYXOWL_SESSION: "1",
      ...(options?.projectPath ? { NYXOWL_PROJECT: options.projectPath } : {}),
    },
  };
}
